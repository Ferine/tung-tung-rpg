#!/usr/bin/env python3
"""The two Impulse Tracker modules smconv packs into the SPC soundbank.

  res/ttsfx.it   one-shot effects. The sample order here *is* the index passed
                 to spcEffect(), so it must match the SFX_* constants in
                 src/ttrpg.h -- which is why the Makefile lists this module
                 first in AUDIOFILES.
  res/ttbgm.it   thirteen themes in one module, as ranges of one order list.

Thirteen themes in one module rather than thirteen modules: spcLoad is a
multi-frame transfer that clears SPC memory (and therefore the loaded effects
with it), and a battle that has to wait for one before the first gauge fills
reads as a hitch. With one module loaded at boot, changing theme is a single
spcPlay(order).

It also writes res/music.h with those ranges, so the module and the C cannot
drift.

The music itself is not in this file. It is written in a small score language
(score.py), for the instruments cut in orchestra.py, in themes_*.py:

    python3 gen_music.py                      build both modules
    python3 gen_music.py --only FIELD TITLE   just these themes, to iterate
"""
import os
import sys

import itwriter as it
import orchestra as orc
import score as sc
import sfx

# The echo. One set of parameters for the whole module -- the driver takes
# them from the song message -- so the difference between a hall and a dry
# room is made per voice, with the S0x echo switch, not per theme.
#   edl   delay in 16ms steps; each step costs 2KB of ARAM
#   efb   feedback: how many repeats
#   evol  return level, left and right
#   efir  eight taps; this is the low-pass from the hardware manual, which
#         takes the top off each repeat so the echo sits behind the music
#         instead of glittering on top of it
#   eon   which voices feed the echo: the tune, the harmony and the ornaments;
#         never the bass or the drums, which turn to mud in a reverb
ECHO = dict(edl=3, efb=34, evol=(26, 26), efir=(-1, 8, 23, 36, 36, 23, 8, -1),
            eon=(1, 3, 4, 5, 7, 8))

# ---- the music module ---------------------------------------------------

# Canonical order: the order themes sit in the module. It is not the BGM_*
# order in ttrpg.h and does not need to be -- audio.c maps one to the other
# through the MUS_*_FIRST names below.
THEME_NAMES = ('TOWN', 'FIELD', 'FOREST', 'SHORE', 'SALT', 'FORTRESS', 'HUSH',
               'BATTLE', 'BOSS', 'FINAL', 'FINAL2', 'FANFARE', 'TITLE', 'ENDING')


def all_themes(names=None):
    import themes
    return themes.build(names or THEME_NAMES)


def song_message():
    e = ECHO
    return ('[[SNESMOD]]\n'
            'edl %d\n'
            'efb %d\n'
            'evol %d %d\n'
            'efir %s\n'
            'eon %s\n' % (e['edl'], e['efb'], e['evol'][0], e['evol'][1],
                           ' '.join(str(v) for v in e['efir']),
                           ' '.join(str(v) for v in e['eon'])))


def build_bgm(themes, report=True):
    """The complete original score, resident as one SPC module."""
    mod = it.Module('TUNG TUNG SAHUR', speed=6, tempo=110, channels=8,
                    global_volume=128, channel_pans=sc.CHAN_PAN,
                    message=song_message())
    names = sc.used_instruments(themes)
    ins = orc.build_instruments(mod, names, report=report)
    ranges = sc.assemble(mod, themes, ins)
    if len(mod.patterns) > 64:
        raise SystemExit('score needs %d patterns; SNESMOD holds 64'
                         % len(mod.patterns))
    if len(mod.orders) > 200:
        raise SystemExit('score needs %d orders; SNESMOD holds 200'
                         % len(mod.orders))
    return mod, ranges


# What smconv leaves for modules out of the SPC's 64KB (it reports this as
# "free" after the first module: 57,957 - the effects module).
ARAM_FOR_MODULES = 57957


def aram_budget(fx, bgm):
    """The bytes the two modules will take, and what is left. smconv's own
    total is samples + pattern data + echo buffer (the effects module adds 9
    bytes for its empty pattern), so this is exact for the samples and echo,
    and within a fifth of a percent for the patterns (the estimate is the
    same packing rule, counted by hand)."""
    import sfsample
    sfx_b = sum(sfsample.brr_bytes(x) for x in fx.samples) + 9
    smp_b = sum(sfsample.brr_bytes(x) for x in bgm.samples)
    pat_b = getattr(bgm, 'pattern_bytes', 0)
    echo_b = ECHO['edl'] * 2048
    total = sfx_b + smp_b + pat_b + echo_b
    return dict(sfx=sfx_b, samples=smp_b, patterns=pat_b, echo=echo_b,
                total=total, free=ARAM_FOR_MODULES - total)


def write_music_header(ranges, path):
    with open(path, 'w') as f:
        f.write("/* Generated by gen_music.py -- do not edit.\n"
                " *\n"
                " * Order ranges of the themes inside res/ttbgm.it. The game\n"
                " * keeps one looping by watching spcGetMusicPosition() and\n"
                " * re-issuing spcPlay when the position leaves the range.\n"
                " * These are order numbers, which is what the SPC reports:\n"
                " * themes share patterns across their order lists, so an\n"
                " * order is not the pattern of the same number. */\n"
                "#ifndef TT_MUSIC_H\n#define TT_MUSIC_H\n\n")
        for name, first, last in ranges:
            f.write("#define MUS_%s_FIRST %d\n" % (name, first))
            f.write("#define MUS_%s_LAST  %d\n" % (name, last))
        f.write("\n#endif\n")


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    only = []
    out = 'res'
    if '--only' in argv:
        i = argv.index('--only')
        for a in argv[i + 1:]:
            if a.startswith('-'):
                break
            only.append(a.upper())
        out = 'res/only'
    if '--out' in argv:
        out = argv[argv.index('--out') + 1]
    os.makedirs(out, exist_ok=True)

    for n in only:
        if n not in THEME_NAMES:
            raise SystemExit('no such theme %s; have: %s'
                             % (n, ', '.join(THEME_NAMES)))
    themes = all_themes(only or None)

    fx = sfx.build()
    n = it.write_it(fx, '%s/ttsfx.it' % out)
    print("%s/ttsfx.it   %d bytes, %d effects" % (out, n, len(fx.samples)))

    bgm, ranges = build_bgm(themes)
    n = it.write_it(bgm, '%s/ttbgm.it' % out)
    print("%s/ttbgm.it   %d bytes, %d patterns, %d orders, %d samples"
          % (out, n, len(bgm.patterns), len(bgm.orders), len(bgm.samples)))
    b = aram_budget(fx, bgm)
    print("ARAM: %d of %d bytes  (effects %d, instruments %d, patterns ~%d, "
          "echo %d)  %s" % (b['total'], ARAM_FOR_MODULES, b['sfx'], b['samples'],
                            b['patterns'], b['echo'],
                            ("%d free" % b['free']) if b['free'] >= 0
                            else "OVER BY %d" % -b['free']))
    if b['free'] < 0 and not only:
        raise SystemExit("the score does not fit in the SPC's memory")
    tb = getattr(bgm, 'theme_bytes', {})
    for name, first, last in ranges:
        print("   %-8s orders %3d..%-3d  %5d bytes of pattern data"
              % (name, first, last, tb.get(name, 0)))
    for t in themes:
        for w in t.warnings:
            print("   note: " + w)
    write_music_header(ranges, '%s/music.h' % out)


if __name__ == '__main__':
    main()
