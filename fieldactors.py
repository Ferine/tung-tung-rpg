"""Dependency-free packing of the separately baked, larger field actors."""
import hashlib
from pathlib import Path

import snesgfx as g

ROOT = Path(__file__).resolve().parent
BAKE = ROOT / 'assets/fieldactors.txt'
SIZE = 32
ANCHOR_X, ANCHOR_Y = 16, 28
PORTRAIT_TILES = {448 + row * 16 + col for row in range(4) for col in range(4)}
GUARDIANS = (('boss_patapim','P_PATAPIM'),('boss_ngantuk','P_TRALA'),
             ('boss_sandking','P_ENEMY'),('boss_crocodilo','P_BOSS'),
             ('boss_silenzio','P_ENEMY'))


def poses():
    out = [('walk.'+d+'.'+str(f), 'P_TUNG', d, f)
           for d in ('down','up','left','right') for f in range(4)]
    for kind,pal in (('villager','P_ENEMY'),('drifter','P_PATAPIM')):
        out += [(kind+'.'+d+'.'+str(f),pal,d,f)
                for d in ('down','up','side') for f in range(2)]
    out += [('cat.side.'+str(f),'P_TUNG','side',f) for f in range(2)]
    return out


def name(index):
    # Slot 28 belongs to the dialogue portrait. Its three neighbours are free.
    block = index if index < 28 else index + 1
    return (block // 4) * 64 + (block % 4) * 4


def digest(palettes):
    h = hashlib.sha256()
    for file in ('gen_fieldactors.py','fieldactors.py','gen_render.py','render_field.py','render_bosses.py','snesgfx.py'):
        h.update(file.encode()+b'\0')
        h.update((ROOT/file).read_bytes().replace(b'\r\n',b'\n'))
    h.update(repr(palettes).encode())
    return h.hexdigest()


def load(palettes):
    lines=BAKE.read_text().splitlines()
    if lines[0] != 'digest '+digest(palettes):
        raise SystemExit('Field actor bake is stale: run python3 gen_fieldactors.py (numpy).')
    actors={}
    for offset in range(1,len(lines),33):
        key=lines[offset].split()[1]
        rows=[[int(c,16) for c in row] for row in lines[offset+1:offset+33]]
        assert len(rows)==32 and all(len(r)==32 for r in rows)
        actors[key]=rows
    assert set(actors)=={p[0] for p in poses()} | {p[0] for p in GUARDIANS}
    return actors


def generate(palettes):
    actors=load(palettes)
    sheet=g.Sheet(512)
    taken=set()
    for i,(key,pal,direction,frame) in enumerate(poses()):
        base=name(i)
        cells={base+y*16+x for y in range(4) for x in range(4)}
        assert not cells & (taken | PORTRAIT_TILES)
        assert max(cells)<512 and base%16<=12 and base%256//16<=12
        taken |= cells
        ox,oy=sheet.origin(base)
        for y,row in enumerate(actors[key]):
            for x,c in enumerate(row): sheet.set(ox+x,oy+y,c)
    g.write('fieldactors.pic',sheet.to_pic())
    guardians=bytearray(2*512)  # village and east road have no guardian
    for key,pal in GUARDIANS:
        rows=actors[key]
        for y in range(0,32,8):
            for x in range(0,32,8):
                guardians += g.tile_bin([row[x:x+8] for row in rows[y:y+8]])
    g.write('fieldguardians.pic',bytes(guardians))
    # Subtle scene-specific fill: preserve identity and bright eyes, cool the
    # forest/void shadows, and warm the shore. These are only OBJ colours.
    tints=((.96,.98,1.04),(1.,1.,1.02),(.91,.99,1.05),
           (1.05,1.02,.95),(.98,.98,1.07),(.94,.99,1.04),(.94,.90,1.10))
    blob=bytearray()
    for tint in tints:
        for palette in palettes:
            blob += g.palette_bin([tuple(min(255,round(c*t)) for c,t in zip(rgb,tint)) for rgb in palette])
    g.write('fieldactors.pal',bytes(blob))
    walk=[name(i) for i in range(16)]
    npc=[name(i) for i in range(16,28)]+[name(28),name(29)]*3
    header=('/* Generated by fieldactors.py via gen_sprites.py. */\n'
            '#ifndef FIELDACTORMAP_H\n#define FIELDACTORMAP_H\n'
            '#define FIELD_ACTOR_BYTES 16384\n'
            '#define FIELD_ANCHOR_X 16\n#define FIELD_ANCHOR_Y 28\n'
            '#define FIELD_GUARDIAN_NAME 460\n'
            'extern char fieldactors_pic, fieldactors_pal;\n'
            'extern char fieldguardians_pic;\n'
            'static const u8 fieldGuardianPal[7] = {0,0,5,1,3,4,3};\n'
            'static const u16 fieldWalk[16] = {%s};\n'
            'static const u16 fieldNpc[18] = {%s};\n'
            '#endif\n') % (', '.join(map(str,walk)),', '.join(map(str,npc)))
    (ROOT/'src/fieldactormap.h').write_text(header)
    print('fieldactors: 30 actor poses, five guardian figures, contact shadows, seven lighting palettes')
